def e(x): return html.escape(str(x), quote=False)

def block(d):
    flow = "\n".join(
      '            <li><span class="en">%s</span><b>%s</b>\n%s</li>' % (
        e(n), e(t), "\n".join('              <p><span>%s</span>%s</p>' % (e(a), e(b)) for a, b in subs))
      for n, t, subs in d["flow"])
    pts = ""
    if d["pts"]:
        items = "\n".join('            <li><i>%02d</i><b>%s</b><p>%s</p></li>' % (i+1, e(t), e(b))
                          for i, (t, b) in enumerate(d["pts"]))
        pts = '\n          <p class="rpanel__ch">%s</p>\n          <ul class="rdeep__pts">\n%s\n          </ul>' % (e(d["pts_h"]), items)
    note2 = '\n          <p class="rdeep__note">%s</p>' % e(d["pts_note"]) if d["pts_note"] else ""
    return f'''
        <!-- ===== ROLEDEEP v1：この職種の「仕事の進め方」と「大切にしていること」。
             出典は WORK の既存パネル／PEOPLE の社員インタビュー本文／JOBS の承認済み求人票／FAQ。
             確認できない業務・制度・実績は書いていない。項目数は職種ごとに異なる。 ===== -->
        <div class="rdeep">
          <h4 class="rdeep__h">{e(d["h"])}</h4>
          <p class="rdeep__lead">{e(d["lead"])}</p>

          <p class="rpanel__ch">{e(d["flow_h"])}</p>
          <ol class="rdeep__flow">
{flow}
          </ol>
          <p class="rdeep__note">{e(d["flow_note"])}</p>{pts}{note2}
        </div>
        <!-- ===== ROLEDEEP v1 END ===== -->
'''

